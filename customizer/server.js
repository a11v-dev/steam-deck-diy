'use strict';

const http = require('http');
const fs = require('fs');
const path = require('path');
const os = require('os');
const crypto = require('crypto');
const { execFile, exec, spawn } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const CONFIG_PATH = path.join(ROOT, 'config.txt');
const EXE_PATH = path.join(ROOT, 'StreamDeckPanel.exe');
const INDEX_PATH = path.join(__dirname, 'index.html');
const CACHE_DIR = path.join(os.tmpdir(), 'streamdeck-icon-cache');
const IMAGES_DIR = path.join(ROOT, 'images');
const HOST = '127.0.0.1';
const PORT = Number(process.env.PORT) || 8787;

const ACTIONS = new Set(['app', 'url', 'cmd', 'key', 'text', 'exit', 'none']);
const DEFAULT_COLOR = '#1E293B';

try { fs.mkdirSync(CACHE_DIR, { recursive: true }); } catch { }
try { fs.mkdirSync(IMAGES_DIR, { recursive: true }); } catch { }

/* ----------------------------- config io ----------------------------- */

function clampInt(value, min, max, fallback) {
  const n = parseInt(value, 10);
  if (!Number.isFinite(n)) return fallback;
  return Math.min(max, Math.max(min, n));
}

function clean(value, max) {
  return String(value == null ? '' : value)
    .replace(/[\r\n|]/g, ' ')
    .trim()
    .slice(0, max);
}

function emptyButton() {
  return { label: '', action: 'none', value: '', color: DEFAULT_COLOR, icon: '' };
}

function parseConfig(text) {
  const state = {
    monitor: 2,
    columns: 4,
    rows: 8,
    showlabels: false,
    title: 'STREAM DECK',
    buttons: []
  };

  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;

    const eq = line.indexOf('=');
    const key = eq > 0 ? line.slice(0, eq).trim().toLowerCase() : '';
    if (key === 'monitor' || key === 'columns' || key === 'rows' ||
        key === 'title' || key === 'showlabels') {
      const val = line.slice(eq + 1).trim();
      if (key === 'title') state.title = val || 'STREAM DECK';
      else if (key === 'showlabels') state.showlabels = val !== '0';
      else state[key] = parseInt(val, 10) || state[key];
      continue;
    }

    const p = line.split('|');
    if (p.length >= 3) {
      state.buttons.push({
        label: clampText(p[0], 40),
        action: normalizeAction(p[1]),
        value: clampText(p[2], 1000),
        color: normalizeColor(p[3]),
        icon: clampText(p[4], 500)
      });
    }
  }

  return normalizeState(state);
}

function clampText(value, max) {
  return String(value == null ? '' : value).trim().slice(0, max);
}

function normalizeAction(action) {
  const a = String(action || '').trim().toLowerCase();
  return ACTIONS.has(a) ? a : 'none';
}

function normalizeColor(color) {
  const c = String(color || '').trim();
  return /^#[0-9a-fA-F]{6}$/.test(c) ? c.toUpperCase() : DEFAULT_COLOR;
}

function normalizeState(input) {
  const src = input || {};
  const state = {
    monitor: clampInt(src.monitor, 1, 9, 2),
    columns: clampInt(src.columns, 1, 12, 4),
    rows: clampInt(src.rows, 1, 12, 8),
    title: clean(src.title, 60) || 'STREAM DECK',
    showlabels: Boolean(src.showlabels),
    buttons: []
  };

  const total = state.columns * state.rows;
  const incoming = Array.isArray(src.buttons) ? src.buttons : [];
  for (let i = 0; i < total; i++) {
    const b = incoming[i] || {};
    state.buttons.push({
      label: clean(b.label, 40),
      action: normalizeAction(b.action),
      value: clean(b.value, 1000),
      color: normalizeColor(b.color),
      icon: clean(b.icon, 500)
    });
  }
  return state;
}

function renderConfig(state) {
  const lines = [
    '# ============================================================',
    '#  STREAM DECK PANEL - config',
    '#  Format: Label|action|value|#color|iconPath',
    '#  Generated by the customizer. You can still edit it by hand.',
    '# ============================================================',
    'monitor=' + state.monitor,
    'columns=' + state.columns,
    'rows=' + state.rows,
    'showlabels=' + (state.showlabels ? 1 : 0),
    'title=' + state.title,
    ''
  ];

  state.buttons.forEach((b, i) => {
    if (i % state.columns === 0) {
      lines.push('# ---------------- Row ' + (i / state.columns + 1) + ' ----------------');
    }
    lines.push([b.label, b.action, b.value, b.color, b.icon].join('|'));
  });

  lines.push('');
  return lines.join('\r\n');
}

function readConfig() {
  let text = '';
  try { text = fs.readFileSync(CONFIG_PATH, 'utf8'); } catch { }
  if (!text.trim()) {
    const state = normalizeState({});
    fs.writeFileSync(CONFIG_PATH, renderConfig(state), 'utf8');
    return state;
  }
  return parseConfig(text);
}

function writeConfig(state) {
  const tmp = CONFIG_PATH + '.tmp';
  fs.writeFileSync(tmp, renderConfig(state), 'utf8');
  fs.renameSync(tmp, CONFIG_PATH);
}

/* ----------------------------- helpers ----------------------------- */

function json(res, code, data) {
  const body = JSON.stringify(data);
  res.writeHead(code, {
    'Content-Type': 'application/json; charset=utf-8',
    'Cache-Control': 'no-store',
    'Content-Length': Buffer.byteLength(body)
  });
  res.end(body);
}

function sendFile(res, file, type, cache) {
  try {
    const data = fs.readFileSync(file);
    res.writeHead(200, {
      'Content-Type': type,
      'Cache-Control': cache || 'no-store',
      'Content-Length': data.length
    });
    res.end(data);
  } catch {
    res.writeHead(404);
    res.end('Not found');
  }
}

function readBody(req, limit, cb) {
  const chunks = [];
  let size = 0;
  let done = false;
  req.on('data', chunk => {
    if (done) return;
    size += chunk.length;
    if (size > limit) {
      done = true;
      cb(new Error('Request body too large'));
      req.destroy();
      return;
    }
    chunks.push(chunk);
  });
  req.on('end', () => {
    if (done) return;
    done = true;
    cb(null, Buffer.concat(chunks).toString('utf8'));
  });
  req.on('error', err => {
    if (done) return;
    done = true;
    cb(err);
  });
}

/* ----------------------------- icons ----------------------------- */

function iconKey(action, value, icon) {
  return crypto.createHash('sha1')
    .update(String(action) + '\u0000' + String(value) + '\u0000' + String(icon))
    .digest('hex');
}

/* ----------------------------- uploads ----------------------------- */

function saveUploadedImage(input) {
  const name = String((input && input.name) || 'image');
  const data = String((input && input.data) || '');
  const match = /^data:image\/(png|jpe?g|bmp|gif);base64,([A-Za-z0-9+/=\s]+)$/i.exec(data);
  if (!match) throw new Error('Use a PNG, JPG, BMP or GIF image');

  let ext = match[1].toLowerCase();
  if (ext === 'jpeg') ext = 'jpg';
  const buffer = Buffer.from(match[2], 'base64');
  if (!buffer.length) throw new Error('The image is empty');
  if (buffer.length > 8 * 1024 * 1024) throw new Error('Image must be under 8 MB');

  const magicOk =
    (ext === 'png' && buffer.slice(0, 4).equals(Buffer.from([0x89, 0x50, 0x4E, 0x47]))) ||
    (ext === 'jpg' && buffer[0] === 0xFF && buffer[1] === 0xD8) ||
    (ext === 'bmp' && buffer[0] === 0x42 && buffer[1] === 0x4D) ||
    (ext === 'gif' && buffer.slice(0, 3).toString('ascii') === 'GIF');
  if (!magicOk) throw new Error('That file is not a valid image');

  const base = name
    .replace(/\.[^.]+$/, '')
    .replace(/[^a-z0-9_-]+/gi, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 40) || 'image';

  const fileName = base + '-' + Date.now().toString(36) + '-' +
    crypto.randomBytes(3).toString('hex') + '.' + ext;
  const fullPath = path.join(IMAGES_DIR, fileName);

  fs.writeFileSync(fullPath, buffer);
  return { path: fullPath, name: fileName };
}

function handleIcon(res, url) {
  const action = clean(url.searchParams.get('action') || '', 12).toLowerCase();
  const value = clean(url.searchParams.get('value') || '', 1000);
  const icon = clean(url.searchParams.get('icon') || '', 500);
  let stamp = '';
  if (icon) {
    try {
      const st = fs.statSync(icon);
      stamp = ':' + st.mtimeMs + ':' + st.size;
    } catch { }
  }
  const key = iconKey(action, value, icon + stamp);
  const png = path.join(CACHE_DIR, key + '.png');

  if (fs.existsSync(png)) {
    return sendFile(res, png, 'image/png', 'public, max-age=31536000, immutable');
  }

  const requestFile = path.join(CACHE_DIR, key + '.req');
  fs.writeFileSync(requestFile, [action, value, icon, png].join('\r\n'), 'utf8');

  execFile(EXE_PATH, ['--icon-request', requestFile],
    { windowsHide: true, timeout: 8000 },
    () => {
      if (fs.existsSync(png)) {
        sendFile(res, png, 'image/png', 'public, max-age=31536000, immutable');
      } else {
        res.writeHead(404, { 'Cache-Control': 'no-store' });
        res.end('No icon');
      }
    });
}

/* ----------------------------- installed apps ----------------------------- */

let appsCache = { at: 0, list: [] };

function listApps() {
  if (Date.now() - appsCache.at < 60000 && appsCache.list.length) return appsCache.list;

  const dirs = [
    process.env.ProgramData && path.join(process.env.ProgramData, 'Microsoft', 'Windows', 'Start Menu', 'Programs'),
    process.env.APPDATA && path.join(process.env.APPDATA, 'Microsoft', 'Windows', 'Start Menu', 'Programs')
  ].filter(Boolean);

  const found = new Map();

  const walk = dir => {
    let entries;
    try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
    for (const entry of entries) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(full);
      } else if (entry.isFile() && entry.name.toLowerCase().endsWith('.lnk')) {
        const name = entry.name.slice(0, -4);
        const k = name.toLowerCase();
        if (!found.has(k)) found.set(k, { name, path: full });
      }
    }
  };

  dirs.forEach(walk);

  const list = [...found.values()]
    .filter(a => a.name.length > 1 && !a.name.startsWith('-'))
    .filter(a => !/^(uninstall|readme|release notes|check for updates|about |documentation|website|manual|license|settings$)/i.test(a.name))
    .sort((a, b) => a.name.localeCompare(b.name));

  appsCache = { at: Date.now(), list };
  return list;
}

/* ----------------------------- deck process ----------------------------- */

function deckRunning(cb) {
  exec('tasklist /FI "IMAGENAME eq StreamDeckPanel.exe" /NH',
    { windowsHide: true, timeout: 5000 },
    (err, stdout) => cb(!err && /StreamDeckPanel\.exe/i.test(stdout || '')));
}

function restartDeck(cb) {
  exec('taskkill /IM StreamDeckPanel.exe /F',
    { windowsHide: true, timeout: 5000 },
    () => {
      setTimeout(() => {
        try {
          const child = spawn(EXE_PATH, [], { cwd: ROOT, detached: true, stdio: 'ignore' });
          child.on('error', () => cb(false));
          child.unref();
          cb(true);
        } catch {
          cb(false);
        }
      }, 700);
    });
}

/* ----------------------------- server ----------------------------- */

const server = http.createServer((req, res) => {
  let url;
  try {
    url = new URL(req.url, 'http://' + HOST + ':' + PORT);
  } catch {
    res.writeHead(400);
    return res.end('Bad request');
  }

  const pathname = url.pathname.replace(/\/+$/, '') || '/';

  try {
    if (req.method === 'GET' && (pathname === '/' || pathname === '/index.html')) {
      return sendFile(res, INDEX_PATH, 'text/html; charset=utf-8');
    }

    if (pathname === '/api/config' && req.method === 'GET') {
      return json(res, 200, readConfig());
    }

    if (pathname === '/api/config' && req.method === 'POST') {
      return readBody(req, 1024 * 1024, (err, body) => {
        if (err) return json(res, 400, { error: err.message });
        let parsed;
        try { parsed = JSON.parse(body); }
        catch { return json(res, 400, { error: 'Invalid JSON' }); }

        const state = normalizeState(parsed);
        writeConfig(state);
        json(res, 200, state);
      });
    }

    if (pathname === '/api/config/raw' && req.method === 'GET') {
      try {
        const text = fs.readFileSync(CONFIG_PATH, 'utf8');
        res.writeHead(200, {
          'Content-Type': 'text/plain; charset=utf-8',
          'Content-Disposition': 'attachment; filename="config.txt"',
          'Cache-Control': 'no-store'
        });
        return res.end(text);
      } catch {
        return json(res, 404, { error: 'config.txt not found' });
      }
    }

    if (pathname === '/api/apps' && req.method === 'GET') {
      return json(res, 200, { apps: listApps() });
    }

    if (pathname === '/api/status' && req.method === 'GET') {
      return deckRunning(running => json(res, 200, { running }));
    }

    if (pathname === '/api/icon' && req.method === 'GET') {
      return handleIcon(res, url);
    }

    if (pathname === '/api/upload' && req.method === 'POST') {
      return readBody(req, 12 * 1024 * 1024, (err, body) => {
        if (err) return json(res, 400, { error: err.message });
        let parsed;
        try { parsed = JSON.parse(body); }
        catch { return json(res, 400, { error: 'Invalid JSON' }); }

        try {
          json(res, 200, saveUploadedImage(parsed));
        } catch (uploadErr) {
          json(res, 400, { error: uploadErr.message });
        }
      });
    }

    if (pathname === '/api/restart' && req.method === 'POST') {
      return restartDeck(ok => json(res, 200, { ok }));
    }

    res.writeHead(404, { 'Content-Type': 'text/plain; charset=utf-8' });
    res.end('Not found');
  } catch (err) {
    json(res, 500, { error: err.message });
  }
});

server.on('error', err => {
  if (err.code === 'EADDRINUSE') {
    console.log('Customizer already running at http://' + HOST + ':' + PORT);
    process.exit(0);
  }
  console.error(err);
  process.exit(1);
});

server.listen(PORT, HOST, () => {
  console.log('Stream Deck customizer running at http://' + HOST + ':' + PORT);
  console.log('Config file: ' + CONFIG_PATH);

  if (process.argv.includes('--open')) {
    try {
      spawn('cmd', ['/c', 'start', '', 'http://' + HOST + ':' + PORT],
        { detached: true, stdio: 'ignore', windowsHide: true }).unref();
    } catch { }
  }
});
